// A spanning tree is a concept from graph theory.

// A subgraph that includes all vertices (nodes) of the original graph
// while forming a tree (no cycles).

// A connected subgraph is said to be spanning tree if and only if :
//  it has all the vertices of the graph
//  v-1 edges connected in acyclic manner

//  A spanning tree:

// ✅ Includes all vertices
// ✅ Is connected
// ✅ Has no cycles
// ✅ Contains exactly:

// n−1

// edges for n vertices.


// What is MST?
// Minimum Spanning Tree (MST)

// If edges have weights:
// (weight/cost/distance)

// Then:
// Minimum Spanning Tree is the spanning tree
// with minimum total edge weight.



// Q1. Can a disconnected graph have a spanning tree?

// ❌ No.

// Because spanning tree must connect all vertices.

// Q2. How many edges in spanning tree?

// For n vertices:

// n−1

// Q3. Can a graph have multiple spanning trees?

// ✅ Yes.

